import { writeFile, readFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildReviewCatalog } from '../business-profile.js';

const output = resolve(fileURLToPath(new URL('../review-catalog.js', import.meta.url)));
const contents = `// Generated by npm run generate. Edit draft-wording.json or keyword-policy.json, collect evidence, then regenerate.\nexport const REVIEW_CATALOG = Object.freeze(${JSON.stringify(buildReviewCatalog(), null, 2)}.map(Object.freeze));\n`;
if (process.argv.includes('--check')) {
  if (await readFile(output, 'utf8') !== contents) throw new Error('Catalog is stale; run npm run generate');
  console.log('Review catalog matches its source configuration.');
} else {
  await writeFile(output, contents);
  console.log('Generated 500 unique keyword-rich business-context drafts.');
}
